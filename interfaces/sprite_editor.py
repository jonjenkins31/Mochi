    def _initial_image_dir(self) -> pathlib.Path:
        path = self.project_root / "characters"
        return path if path.is_dir() else self.project_root

    def _initial_script_dir(self) -> pathlib.Path:
        path = self.project_root / "assets" / "mscripts"
        return path if path.is_dir() else self.project_root

    def open_image(self) -> None:
        filename, _ = self._QtWidgets.QFileDialog.getOpenFileName(
            self.widget, "Open sprite atlas", str(self._initial_image_dir()),
            "Images (*.png *.bmp *.jpg *.jpeg *.webp);;All files (*)")
        if filename:
            self.load_image(pathlib.Path(filename), reset=True)

    def load_image(self, path: pathlib.Path, *, reset: bool = False) -> bool:
        pixmap = self._QtGui.QPixmap(str(path))
        if pixmap.isNull():
            self._QtWidgets.QMessageBox.critical(
                self.widget, "Image failed", f"Could not load {path}")
            return False
        self.image_path = path.resolve()
        self.pixmap = pixmap
        if reset:
            self.current_path = None
            self.sprites = []
            self.timeline = []
        self._rebuild_scene()
        self._refresh_sprites()
        self._refresh_timeline()
        self.status.setText(str(path))
        return True

    def load_character(self, character: Any) -> bool:
        """Load a sprite character's active atlas and declared regions.

        Character packs normally address a regular grid rather than an
        MScript timeline.  Expanding that grid here makes the same region
        editor useful for both formats, while the manifest remains the
        authoritative mapping.
        """
        if character.kind != "sprite_sheet":
            return False
        manifest = yaml.safe_load(
            (character.root / "character.yaml").read_text(encoding="utf-8")) or {}
        assets = []
        for name, spec in (manifest.get("assets") or {}).items():
            if not isinstance(spec, dict) or not spec.get("file"):
                continue
            if spec.get("type") != "sprite_sheet" and spec.get("adapter") != "sprite":
                continue
            assets.append({
                "name": str(name),
                "file": str(spec["file"]),
                "properties": str(spec.get("properties", "")),
                "layout": str(spec.get("layout", "")),
            })
        if not assets:
            assets.append({
                "name": "active", "file": str(character.render["asset"]),
                "properties": "", "layout": "grid",
            })

        self._character = character
        self._character_assets = assets
        self.character_asset_box.blockSignals(True)
        self.character_asset_box.clear()
        for asset in assets:
            self.character_asset_box.addItem(asset["name"], asset)
        preferred = str(manifest.get("default_asset", ""))
        selected = max(0, self.character_asset_box.findText(preferred))
        self.character_asset_box.setCurrentIndex(selected)
        self.character_asset_box.blockSignals(False)
        self.character_asset_label.show()
        self.character_asset_box.show()
        return self._load_character_asset(assets[selected])

    def _on_character_asset_picked(self, index: int) -> None:
        if index >= 0 and hasattr(self, "_character_assets"):
            self._load_character_asset(self._character_assets[index])

    def _load_character_asset(self, asset: dict[str, str]) -> bool:
        character = self._character
        image_path = character.root / asset["file"]
        if not self.load_image(image_path, reset=True):
            return False

        properties: dict[str, Any] = {}
        properties_path = asset.get("properties")
        if properties_path:
            try:
                properties = yaml.safe_load(
                    (character.root / properties_path).read_text(encoding="utf-8")) or {}
            except (OSError, yaml.YAMLError) as exc:
                self.status.setText(f"Could not read {properties_path}: {exc}")

        rectangles: list[list[int]] = []
        property_sprites = properties.get("sprites") or {}
        for spec in property_sprites.values():
            src = spec.get("src")
            if src and len(src) == 4:
                rect = [int(value) for value in src]
                if rect not in rectangles:
                    rectangles.append(rect)

        grid = properties.get("grid")
        if not grid and asset["file"] == str(character.render["asset"]):
            grid = character.grid
        if not rectangles and grid:
            columns, rows = int(grid[0]), int(grid[1])
            cell_size = properties.get("cell_size") or character.render.get("cell_size") or [
                self.pixmap.width() // columns,
                self.pixmap.height() // rows,
            ]
            width, height = (int(cell_size[0]), int(cell_size[1]))
            rectangles = [
                [column * width, row * height, width, height]
                for row in range(rows) for column in range(columns)
            ]

        self.sprites = rectangles
        self.timeline = []
        selected_sprite = 0
        active_asset = asset["file"] == str(character.render["asset"])
        if active_asset:
            state_row = int(character.mouth_states.get(character.default_mouth, 0))
            columns = character.grid[0] if character.grid else 1
            indices = []
            for spec in character.expressions.values():
                if "src" in spec:
                    rect = [int(value) for value in spec["src"]]
                    index = self.sprites.index(rect)
                elif "cell" in spec:
                    index = int(spec["cell"])
                else:
                    index = state_row * columns + int(spec.get("column", 0))
                indices.append(index)
            default_spec = character.expressions.get(
                character.default_expression, {})
            if "src" in default_spec:
                selected_sprite = self.sprites.index(
                    [int(value) for value in default_spec["src"]])
            elif "cell" in default_spec:
                selected_sprite = int(default_spec["cell"])
            else:
                selected_sprite = (
                    state_row * columns + int(default_spec.get("column", 0)))
        else:
            indices = list(range(len(self.sprites)))
            default_region = str(properties.get("default", ""))
            if default_region in property_sprites:
                default_rect = [
                    int(value) for value in property_sprites[default_region]["src"]]
                selected_sprite = self.sprites.index(default_rect)
        for index in indices:
            if 0 <= index < len(self.sprites):
                self.timeline.extend((
                    {"cmd": "sprite", "index": index},
                    {"cmd": "delay", "duration": 0.5},
                ))
        self._refresh_sprites()
        self._refresh_timeline()
        self._rebuild_scene()
        if self.sprites:
            self.sprite_list.setCurrentRow(
                selected_sprite if 0 <= selected_sprite < len(self.sprites) else 0)
        self.status.setText(
            f"{character.display_name or character.name} — "
            f"{asset['name']} — {len(self.sprites)} regions"
        )
        return True

    def open_script(self) -> None:
        filename, _ = self._QtWidgets.QFileDialog.getOpenFileName(
            self.widget, "Open sprite MScript", str(self._initial_script_dir()),
            "MochiScript (*.mscript);;All files (*)")
        if not filename:
            return
        path = pathlib.Path(filename)
        try:
            resource_id, image_value, sprites, timeline = parse_sprite_script(
                path.read_text(encoding="utf-8"))
        except Exception as exc:  # noqa: BLE001
            self._QtWidgets.QMessageBox.critical(
                self.widget, "Open failed", str(exc))
            return
        image_path = pathlib.Path(image_value)
        if not image_path.is_absolute():
            candidates = (path.parent / image_path, self.project_root / image_path)
            image_path = next((candidate for candidate in candidates if candidate.is_file()),
                              candidates[0])
        self.image_resource_id = resource_id
        self.sprites = sprites
        self.timeline = timeline
        self.current_path = path
        if self.load_image(image_path):
            self.status.setText(str(path))

    def _image_reference(self) -> str:
        if self.image_path is None:
            return ""
        try:
            return self.image_path.relative_to(self.project_root).as_posix()
        except ValueError:
            return str(self.image_path)

    def save_script(self) -> bool:
        return self._write(self.current_path) if self.current_path else self.save_script_as()

    def save_script_as(self) -> bool:
        filename, _ = self._QtWidgets.QFileDialog.getSaveFileName(
            self.widget, "Save sprite MScript",
            str(self._initial_script_dir() / "sprite.mscript"),
            "MochiScript (*.mscript)")
        if not filename:
            return False
        path = pathlib.Path(filename)
        if not path.suffix:
            path = path.with_suffix(".mscript")
        return self._write(path)

    def _write(self, path: pathlib.Path | None) -> bool:
        if path is None or self.image_path is None:
            self._QtWidgets.QMessageBox.warning(
                self.widget, "Nothing to save", "Open an atlas image first.")
            return False
        try:
            content = build_sprite_script(
                self.image_resource_id, self._image_reference(),
                self.sprites, self.timeline)
            path.write_text(content, encoding="utf-8")
        except Exception as exc:  # noqa: BLE001
            self._QtWidgets.QMessageBox.critical(
                self.widget, "Save failed", str(exc))
            return False
        self.current_path = path
        self.status.setText(f"Saved {path}")
        return True

    def create_sprite(self) -> None:
        if self.pixmap.isNull():
            return
        width, height = self.new_width.value(), self.new_height.value()
        x = max(0, (self.pixmap.width() - width) // 2)
        y = max(0, (self.pixmap.height() - height) // 2)
        self.sprites.append([x, y, width, height])
        self._refresh_sprites()
        self._rebuild_scene()
        self.sprite_list.setCurrentRow(len(self.sprites) - 1)

    def duplicate_sprite(self) -> None:
        row = self.sprite_list.currentRow()
        if row < 0:
            return
        x, y, width, height = self.sprites[row]
        self.sprites.append([x + 10, y + 10, width, height])
        self._refresh_sprites()
        self._rebuild_scene()
        self.sprite_list.setCurrentRow(len(self.sprites) - 1)

    def delete_sprite(self) -> None:
        row = self.sprite_list.currentRow()
        if row < 0:
            return
        del self.sprites[row]
        updated = []
        for item in self.timeline:
            if item["cmd"] != "sprite":
                updated.append(item)
            elif item["index"] < row:
                updated.append(item)
            elif item["index"] > row:
                updated.append({**item, "index": item["index"] - 1})
        self.timeline = updated
        self._refresh_sprites()
        self._refresh_timeline()
        self._rebuild_scene()

    def _refresh_sprites(self) -> None:
        row = self.sprite_list.currentRow() if hasattr(self, "sprite_list") else -1
        self.sprite_list.clear()
        self.sprite_list.addItems([
            f"Sprite {index}: [{x}, {y}, {width}, {height}]"
            for index, (x, y, width, height) in enumerate(self.sprites)
        ])
        if 0 <= row < len(self.sprites):
            self.sprite_list.setCurrentRow(row)

    def _rebuild_scene(self) -> None:
        self._syncing = True
        self.scene.clear()
        self._rect_items = []
        if not self.pixmap.isNull():
            background = self.scene.addPixmap(self.pixmap)
            background.setZValue(-10)
            self.scene.setSceneRect(0, 0, self.pixmap.width(), self.pixmap.height())
        flags = (self._QtWidgets.QGraphicsItem.ItemIsMovable
                 | self._QtWidgets.QGraphicsItem.ItemIsSelectable
                 | self._QtWidgets.QGraphicsItem.ItemSendsGeometryChanges)
        for index, (x, y, width, height) in enumerate(self.sprites):
            item = self.scene.addRect(
                x, y, width, height,
                self._QtGui.QPen(self._QtGui.QColor("#30d5ff"), 2),
                self._QtGui.QBrush(self._QtCore.Qt.NoBrush),
            )
            item.setFlags(flags)
            item.setData(0, index)
            item.setZValue(5)
            self._rect_items.append(item)
        self._syncing = False

    def _select_sprite(self, row: int) -> None:
        if self._syncing:
            return
        self._syncing = True
        for index, item in enumerate(self._rect_items):
            item.setSelected(index == row)
            item.setPen(self._QtGui.QPen(
                self._QtGui.QColor("#ffe066" if index == row else "#30d5ff"), 2))
        if 0 <= row < len(self.sprites):
            for spin, value in zip(self.rect_spins, self.sprites[row]):
                spin.setValue(value)
            self._show_sprite(row)
        self._syncing = False

    def _scene_selection_changed(self) -> None:
        if self._syncing or self._closing:
            return
        try:
            selected = self.scene.selectedItems()
        except RuntimeError:
            return
        if selected:
            self.sprite_list.setCurrentRow(int(selected[0].data(0)))

    def _scene_changed(self, _regions=None) -> None:
        if self._syncing or self._closing:
            return
        row = self.sprite_list.currentRow()
        if not 0 <= row < len(self._rect_items):
            return
        item = self._rect_items[row]
        rect = item.rect()
        pos = item.pos()
        values = [round(rect.x() + pos.x()), round(rect.y() + pos.y()),
                  round(rect.width()), round(rect.height())]
        if values != self.sprites[row]:
            self.sprites[row] = values
            self._syncing = True
            for spin, value in zip(self.rect_spins, values):
                spin.setValue(value)
            self._refresh_sprites()
            self.sprite_list.setCurrentRow(row)
            self._syncing = False
            self._show_sprite(row)

    def _geometry_changed(self, _value: int) -> None:
        if self._syncing:
            return
        row = self.sprite_list.currentRow()
        if not 0 <= row < len(self.sprites):
            return
        values = [spin.value() for spin in self.rect_spins]
        self.sprites[row] = values
        item = self._rect_items[row]
        self._syncing = True
        item.setPos(0, 0)
        item.setRect(*values)
        self._refresh_sprites()
        self.sprite_list.setCurrentRow(row)
        self._syncing = False
        self._show_sprite(row)

    def add_sprite_to_timeline(self) -> None:
        row = self.sprite_list.currentRow()
        if row < 0:
            return
        self.timeline.append({"cmd": "sprite", "index": row})
        self._refresh_timeline()
        self.timeline_list.setCurrentRow(len(self.timeline) - 1)

    def add_delay(self) -> None:
        self.timeline.append({"cmd": "delay", "duration": self.delay.value()})
        self._refresh_timeline()
        self.timeline_list.setCurrentRow(len(self.timeline) - 1)

    def remove_timeline_item(self) -> None:
        row = self.timeline_list.currentRow()
        if row >= 0:
            del self.timeline[row]
            self._refresh_timeline()

    def move_timeline_item(self, direction: int) -> None:
        row = self.timeline_list.currentRow()
        target = row + direction
        if row >= 0 and 0 <= target < len(self.timeline):
            self.timeline.insert(target, self.timeline.pop(row))
            self._refresh_timeline()
            self.timeline_list.setCurrentRow(target)

    def _refresh_timeline(self) -> None:
        self.timeline_list.clear()
        labels = []
        for index, item in enumerate(self.timeline):
            if item["cmd"] == "sprite":
                labels.append(f"{index}: SHOW Sprite {item['index']}")
            else:
                labels.append(f"{index}: DELAY {float(item['duration']):g}s")
        self.timeline_list.addItems(labels)

    def _show_sprite(self, index: int) -> None:
        if self.pixmap.isNull() or not 0 <= index < len(self.sprites):
            return
        x, y, width, height = self.sprites[index]
        cropped = self.pixmap.copy(x, y, width, height)
        self.preview.setPixmap(cropped.scaled(
            self.preview.size(), self._QtCore.Qt.KeepAspectRatio,
            self._QtCore.Qt.FastTransformation))
        if self._on_preview is not None and self.image_path is not None:
            self._on_preview(self.image_path, [x, y, width, height])

    def toggle_preview(self) -> None:
        if self._playing:
            self._stop_preview()
            return
        if not self.timeline:
            return
        self._playing = True
        self._preview_index = 0
        self.play_button.setText("Stop")
        self._advance_preview()

    def _advance_preview(self) -> None:
        if not self._playing or not self.timeline:
            return
        if self._preview_index >= len(self.timeline):
            self._preview_index = 0
        row = self._preview_index
        item = self.timeline[row]
        self.timeline_list.setCurrentRow(row)
        self._preview_index += 1
        delay_ms = 1
        if item["cmd"] == "sprite":
            self._show_sprite(int(item["index"]))
        else:
            delay_ms = max(1, round(float(item["duration"]) * 1000))
        self.preview_timer.start(delay_ms)

    def _stop_preview(self) -> None:
        self._playing = False
        self.preview_timer.stop()
        self.play_button.setText("Play")

    def close(self) -> None:
        self._closing = True
        self._stop_preview()
        try:
            self.scene.selectionChanged.disconnect(self._scene_selection_changed)
            self.scene.changed.disconnect(self._scene_changed)
        except (RuntimeError, TypeError):
            pass



        create_layout = QtWidgets.QFormLayout(create_group)
        self.new_width = QtWidgets.QSpinBox()
        self.new_height = QtWidgets.QSpinBox()
        for spin in (self.new_width, self.new_height):
            spin.setRange(1, 10000)

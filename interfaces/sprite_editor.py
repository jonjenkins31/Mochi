"""Integrated sprite-region and timeline editor, ported from Mochi 3.0."""

from __future__ import annotations

import pathlib
import re
from typing import Any

import yaml

from .mscript_editor import parse_mscript, parse_resources


_SPRITE = re.compile(
    r"^SPRITE\s+(K\[\d+\])(?:\s+D\[([\d.]+)\])?\s+"
    r"SRC\[(-?\d+),(-?\d+),(\d+),(\d+)\]\s*$",
    re.IGNORECASE,
)
_WAIT = re.compile(r"^WAIT\s+D\[([\d.]+)\]\s*$", re.IGNORECASE)


def parse_sprite_script(
    text: str,
) -> tuple[str, str, list[list[int]], list[dict[str, Any]]]:
    """Return resource id/path, unique sprite rectangles, and timeline."""
    sections = parse_mscript(text)
    resources = parse_resources(sections.get("resources", []))
    if not resources:
        raise ValueError("No image resource was declared in [Resources].")
    resource_id, image_path = resources[0]
    sprites: list[list[int]] = []
    timeline: list[dict[str, Any]] = []
    for line in sections.get("main", []):
        sprite = _SPRITE.match(line.strip())
        wait = _WAIT.match(line.strip())
        if sprite:
            _resource, duration, x, y, width, height = sprite.groups()
            rect = [int(x), int(y), int(width), int(height)]
            if rect not in sprites:
                sprites.append(rect)
            timeline.append({"cmd": "sprite", "index": sprites.index(rect)})
            if duration is not None and float(duration) > 0:
                timeline.append({"cmd": "delay", "duration": float(duration)})
        elif wait:
            timeline.append({"cmd": "delay", "duration": float(wait.group(1))})
    return resource_id, image_path, sprites, timeline


def build_sprite_script(
    resource_id: str,
    image_path: str,
    sprites: list[list[int]],
    timeline: list[dict[str, Any]],
) -> str:
    """Serialize a sprite timeline using the legacy-compatible grammar."""
    output = [
        "[Header start]",
        "! Generated by Mochi Sprite Editor",
        "[Header end]",
        "",
        "[Resources start]",
        f"{resource_id}: '{image_path}'",
        "[Resources end]",
        "",
        "[Main start]",
    ]
    index = 0
    while index < len(timeline):
        item = timeline[index]
        if item["cmd"] == "sprite":
            sprite_index = int(item["index"])
            if not 0 <= sprite_index < len(sprites):
                raise ValueError(f"Timeline references missing sprite {sprite_index}.")
            x, y, width, height = sprites[sprite_index]
            duration = 0.0
            if index + 1 < len(timeline) and timeline[index + 1]["cmd"] == "delay":
                duration = float(timeline[index + 1]["duration"])
                index += 1
            output.append(
                f"SPRITE {resource_id} D[{duration:g}] "
                f"SRC[{x},{y},{width},{height}]"
            )
        elif item["cmd"] == "delay":
            output.append(f"WAIT D[{float(item['duration']):g}]")
        index += 1
    output.extend(["[Main end]", ""])
    return "\n".join(output)


class SpriteEditorTab:
    """Qt sprite atlas editor with draggable regions and a timed preview."""

    def __init__(self, app: Any, qt: tuple, on_preview: Any = None) -> None:
        QtCore, QtGui, QtWidgets = qt
        self._QtCore, self._QtGui, self._QtWidgets = QtCore, QtGui, QtWidgets
        self.project_root = pathlib.Path(__file__).resolve().parent.parent
        self.current_path: pathlib.Path | None = None
        self.image_path: pathlib.Path | None = None
        self.image_resource_id = "K[1]"
        self.pixmap = QtGui.QPixmap()
        self.sprites: list[list[int]] = []
        self.timeline: list[dict[str, Any]] = []
        self._rect_items: list[Any] = []
        self._syncing = False
        self._closing = False
        self._playing = False
        self._preview_index = 0
        self._on_preview = on_preview

        self.widget = QtWidgets.QWidget()
        root = QtWidgets.QVBoxLayout(self.widget)
        root.setContentsMargins(8, 8, 8, 8)

        toolbar = QtWidgets.QHBoxLayout()
        for label, callback in (
            ("Open Script…", self.open_script),
            ("Open Image…", self.open_image),
            ("Save", self.save_script),
            ("Save As…", self.save_script_as),
        ):
            button = QtWidgets.QPushButton(label)
            button.clicked.connect(callback)
            toolbar.addWidget(button)
        self.character_asset_label = QtWidgets.QLabel("Character asset")
        self.character_asset_box = QtWidgets.QComboBox()
        self.character_asset_box.setMinimumWidth(180)
        self.character_asset_box.currentIndexChanged.connect(
            self._on_character_asset_picked)
        self.character_asset_label.hide()
        self.character_asset_box.hide()
        toolbar.addWidget(self.character_asset_label)
        toolbar.addWidget(self.character_asset_box)
        toolbar.addStretch(1)
        root.addLayout(toolbar)

        splitter = QtWidgets.QSplitter(QtCore.Qt.Horizontal)
        root.addWidget(splitter, 1)
        splitter.addWidget(self._build_sprite_panel())
        splitter.addWidget(self._build_canvas())
        splitter.addWidget(self._build_timeline_panel())
        splitter.setSizes([250, 650, 290])

        self.status = QtWidgets.QLabel("Open an image or sprite MScript")
        root.addWidget(self.status)

        self.preview_timer = QtCore.QTimer(self.widget)
        self.preview_timer.setSingleShot(True)
        self.preview_timer.timeout.connect(self._advance_preview)


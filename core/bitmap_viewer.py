def bytes_per_row():
    return (SRC_W + 7) // 8

def bit_on(x, y, msb_first=True):
    if not (0 <= x < SRC_W and 0 <= y < SRC_H):
        return False
    bpr = bytes_per_row()
    idx = y * bpr + (x // 8)
    if idx >= len(BITMAP):
        return False
    bit = 7 - (x % 8) if msb_first else (x % 8)
    return ((BITMAP[idx] >> bit) & 1) != 0

class App:
    def __init__(self, root):
        self.root = root
        root.title("Bitmap Viewer")

        self.display_w = tk.IntVar(value=64)
        self.display_h = tk.IntVar(value=32)
        self.scale = tk.IntVar(value=6)      # canvas pixel scale
        self.ox = tk.IntVar(value=None if True else 0) # leave None behavior in code
        self.oy = tk.IntVar(value=None if True else 0)

        self.msb_first = tk.BooleanVar(value=True)
        self.transpose = tk.BooleanVar(value=False)
        self.flip_x = tk.BooleanVar(value=False)
        self.flip_y = tk.BooleanVar(value=False)
        self.mode = tk.StringVar(value="noscale")  # "noscale" or "scale"

        # Controls
        ctrl = ttk.Frame(root, padding=6); ctrl.pack(side=tk.TOP, fill=tk.X)
        ttk.Label(ctrl, text="Display W").grid(row=0, column=0, sticky="w")
        ttk.Entry(ctrl, textvariable=self.display_w, width=6).grid(row=0, column=1)
        ttk.Label(ctrl, text="Display H").grid(row=0, column=2, sticky="w", padx=(8,0))
        ttk.Entry(ctrl, textvariable=self.display_h, width=6).grid(row=0, column=3)

        ttk.Label(ctrl, text="Scale").grid(row=0, column=4, sticky="w", padx=(8,0))
        ttk.Entry(ctrl, textvariable=self.scale, width=4).grid(row=0, column=5)

        ttk.Radiobutton(ctrl, text="1:1 (crop/center)", variable=self.mode, value="noscale").grid(row=0, column=6, padx=8)
        ttk.Radiobutton(ctrl, text="Scale to fit", variable=self.mode, value="scale").grid(row=0, column=7)

        ttk.Checkbutton(ctrl, text="MSB-first", variable=self.msb_first).grid(row=1, column=0, sticky="w", pady=4)
        ttk.Checkbutton(ctrl, text="Transpose", variable=self.transpose).grid(row=1, column=1, sticky="w")
        ttk.Checkbutton(ctrl, text="Flip X", variable=self.flip_x).grid(row=1, column=2, sticky="w")
        ttk.Checkbutton(ctrl, text="Flip Y", variable=self.flip_y).grid(row=1, column=3, sticky="w")

        self.redraw_btn = ttk.Button(ctrl, text="Redraw", command=self.redraw)
        self.redraw_btn.grid(row=1, column=7, sticky="e")

        # Canvas
        self.canvas = tk.Canvas(root, bg="#111111", width=400, height=250, highlightthickness=0)
        self.canvas.pack(fill=tk.BOTH, expand=True)
        # Redraw on resize
        self.canvas.bind("<Configure>", lambda e: self.redraw())

        self.redraw()

    def map_src(self, x, y):
        # apply transpose + flips
        if self.transpose.get():
            x, y = y, x
        if self.flip_x.get():
            x = SRC_W - 1 - x
        if self.flip_y.get():
            y = SRC_H - 1 - y
        return x, y

    def redraw(self):
        self.canvas.delete("all")
        try:
            W = max(1, int(self.display_w.get()))
            H = max(1, int(self.display_h.get()))
            SCALE = max(1, int(self.scale.get()))
        except Exception:
            return

        cw, ch = W * SCALE, H * SCALE
        self.canvas.config(width=cw, height=ch)

        msb = self.msb_first.get()
        mode = self.mode.get()

        # background grid (optional)
        # for y in range(H):
        #     self.canvas.create_line(0, y*SCALE, cw, y*SCALE, fill="#222")
        # for x in range(W):
        #     self.canvas.create_line(x*SCALE, 0, x*SCALE, ch, fill="#222")

        if mode == "scale":
            # nearest-neighbor mapping from display -> source
            for y in range(H):
                sy = int(y * (SRC_H / H))
                if sy >= SRC_H: sy = SRC_H - 1
                for x in range(W):
                    sx = int(x * (SRC_W / W))
                    if sx >= SRC_W: sx = SRC_W - 1
                    sx, sy2 = self.map_src(sx, sy)
                    on = bit_on(sx, sy2, msb_first=msb)
                    if on:
                        x0, y0 = x*SCALE, y*SCALE
                        self.canvas.create_rectangle(x0, y0, x0+SCALE, y0+SCALE, outline="", fill="#1ed760")
        else:
            # 1:1 blit center/crop
            ox = (W - SRC_W) // 2
            oy = (H - SRC_H) // 2
            x0 = max(0, -ox)
            y0 = max(0, -oy)
            x1 = min(SRC_W, W - ox)
            y1 = min(SRC_H, H - oy)
            for sy in range(y0, y1):
                for sx in range(x0, x1):
                    mx = sx + ox
                    my = sy + oy
                    sx2, sy2 = self.map_src(sx, sy)
                    on = bit_on(sx2, sy2, msb_first=msb)
                    if on and 0 <= mx < W and 0 <= my < H:
                        x0p, y0p = mx*SCALE, my*SCALE
                        self.canvas.create_rectangle(x0p, y0p, x0p+SCALE, y0p+SCALE, outline="", fill="#1ed760")


